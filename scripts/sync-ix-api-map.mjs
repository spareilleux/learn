// Generates the "Every crate and every public function" appendix of the machine learning course,
// in the three locales, from a local IX checkout at the commit the course pins.
//
//   npm run sync:ix-api-map -- --ix ../ix
//
// The appendix lists every `pub fn`, `pub struct`, `pub enum`, `pub trait`, `pub const` and
// `pub type` declared under `crates/*/src/`, read out of the pinned commit with `git grep`, so it
// never depends on the working tree of the IX clone. Never edit the generated pages by hand.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const args = process.argv.slice(2);
const ixIndex = args.indexOf('--ix');
const ixPath = resolve(root, ixIndex === -1 ? '../ix' : args[ixIndex + 1]);

// The revision the course depends on, read from the course's Cargo.toml so the two cannot drift
const cargo = readFileSync(join(root, 'code/machine-learning-ix/Cargo.toml'), 'utf8');
const revisions = [...cargo.matchAll(/rev = "([0-9a-f]{40})"/g)].map((m) => m[1]);
const rev = revisions[0];
if (!rev || revisions.some((r) => r !== rev)) {
  throw new Error(`code/machine-learning-ix/Cargo.toml must pin every IX crate to one revision, found ${[...new Set(revisions)].join(', ')}`);
}
const short = rev.slice(0, 7);

const git = (...a) => execFileSync('git', ['-C', ixPath, ...a], { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] });

// One `git grep` for every public declaration in the workspace, at the pinned commit
const KINDS = ['fn', 'struct', 'enum', 'trait', 'const', 'type'];
const declarations = git(
  'grep', '-n', '-E', `^[[:space:]]*pub (${KINDS.join('|')}) `, rev, '--', 'crates',
)
  .split('\n')
  .filter((line) => line.includes('/src/'));

/** crate -> module path -> kind -> sorted names */
const crates = new Map();
for (const line of declarations) {
  const match = line.match(/^[0-9a-f]{40}:crates\/([^/]+)\/src\/(.+?):\d+:\s*pub (\w+) ([A-Za-z_][A-Za-z0-9_]*)/);
  if (!match) continue;
  const [, crate, file, kind, name] = match;
  if (!KINDS.includes(kind)) continue;
  // `src/foo/bar.rs` is module `foo::bar`; `src/lib.rs` is the crate root
  const modulePath = file === 'lib.rs'
    ? '(crate root)'
    : file.replace(/\.rs$/, '').replace(/\/mod$/, '').replaceAll('/', '::');
  if (!crates.has(crate)) crates.set(crate, new Map());
  const modules = crates.get(crate);
  if (!modules.has(modulePath)) modules.set(modulePath, new Map());
  const kinds = modules.get(modulePath);
  if (!kinds.has(kind)) kinds.set(kind, new Set());
  kinds.get(kind).add(name);
}

// The first sentence of each crate's `//!` header, for a one-line description
const summaries = new Map();
for (const crate of crates.keys()) {
  let lib = '';
  try {
    lib = git('show', `${rev}:crates/${crate}/src/lib.rs`);
  } catch {
    continue;
  }
  const doc = lib
    .split('\n')
    .filter((l) => l.startsWith('//!'))
    .map((l) => l.slice(3).trim())
    .filter((l) => l && !l.startsWith('#') && !l.startsWith('```'));
  if (!doc.length) continue;
  // The header wraps over several lines: join them, then keep the first whole sentence
  const joined = doc.join(' ').replace(/\s+/g, ' ');
  const sentence = joined.match(/^(.*?)(?:\.(?:\s|$)|$)/)[1].trim();
  const summary = (sentence.length > 160 ? `${sentence.slice(0, 157)}…` : sentence).replace(/[,;:]$/, '');
  if (summary) summaries.set(crate, summary);
}

const sortedCrates = [...crates.keys()].sort();
const total = (kind) => sortedCrates.reduce(
  (sum, c) => sum + [...crates.get(c).values()].reduce((s, m) => s + (m.get(kind)?.size ?? 0), 0),
  0,
);
const counts = Object.fromEntries(KINDS.map((k) => [k, total(k)]));
const grandTotal = Object.values(counts).reduce((a, b) => a + b, 0);

